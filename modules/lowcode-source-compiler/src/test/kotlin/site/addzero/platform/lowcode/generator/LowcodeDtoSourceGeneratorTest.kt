    @Test
    fun `generates empty structure as marker class`() {
        val definition = LsiLowcodeDtoDefinition(
            dtoCode = "marker",
            name = "标记结构",
            packageName = "example.marker",
            className = "Marker",
            kind = LowcodeDtoKind.STRUCTURE,
            contributorId = "example.example",
            fields = emptyList(),
        )

        val file = LowcodeDtoSourceGenerator.generateDefinitions(listOf(definition), emptyList()).single()

        assertTrue(file.content.contains("class Marker"))
        assertFalse(file.content.contains("data class Marker"))
    }

    @Test
    fun `generates structure dto from qualified Kotlin types without OpenAPI exposure`() {
        val definition = LsiLowcodeDtoDefinition(
            dtoCode = "toolSet",
            name = "工具集合",
            packageName = "example.tools",
            className = "ToolSet",
            kind = LowcodeDtoKind.STRUCTURE,
            contributorId = "example.example",
            fields = listOf(
                LsiLowcodeDtoField(
                    name = "registry",
                    nullability = LowcodeDtoNullability.NON_NULL,
                    kotlinType = LsiDtoType("example.registry.ToolRegistry"),
                ),
                LsiLowcodeDtoField(
                    name = "policies",
                    nullability = LowcodeDtoNullability.NON_NULL,
                    kotlinType = LsiDtoType.map(
                        LsiDtoType.STRING,
                        LsiDtoType("example.policy.ToolPolicy"),
                    ),
                ),
            ),
        )

        val file = LowcodeDtoSourceGenerator.generateDefinitions(listOf(definition), emptyList()).single()

        assertEquals(LowcodeGeneratedFileKind.COMPILED_SOURCE, file.kind)
        assertTrue(file.content.startsWith("// generated by studio"))
        assertTrue(file.content.contains("import example.policy.ToolPolicy"))
        assertTrue(file.content.contains("import example.registry.ToolRegistry"))
        assertTrue(file.content.contains("data class ToolSet"))
        assertTrue(file.content.contains("val policies: Map<String, ToolPolicy>"))
        assertThrows(IllegalArgumentException::class.java) { definition.toLsiDtoSchema() }
        assertTrue(LowcodeDtoSourceGenerator.generateDefinitionValidations(listOf(definition), emptyList()).isEmpty())
    }

    @Test
    fun `generates validation extension beside standalone input dto`() {
        val definition = LsiLowcodeDtoDefinition(
            dtoCode = "exampleCommand",
            name = "示例命令",
            packageName = "example.command",
            className = "ExampleCommand",
            kind = LowcodeDtoKind.INPUT,
            contributorId = "example.example",
            fields = listOf(
                LsiLowcodeDtoField(
                    name = "name",
                    nullability = LowcodeDtoNullability.NON_NULL,
                    schema = LsiLowcodeApiSchema(type = "string"),
                    validations = listOf(LsiValidationRule("notBlank", "名称不能为空")),
                ),
            ),
        )

        val file = LowcodeDtoSourceGenerator.generateDefinitionValidations(
            listOf(definition),
            emptyList(),
        ).single()

        assertEquals("ExampleCommandValidation", file.fileName)
        assertEquals("example.command.generated.dto", file.packageName)
        assertTrue(file.content.contains("fun ExampleCommand.validate(): ExampleCommand"))
        assertTrue(file.content.contains("this@validate.name.isBlank()"))
        assertTrue(file.content.contains("throw ValidationException"))
    }

    @Test
    fun `generates standalone dto without an entity model`() {
        val definition = LsiLowcodeDtoDefinition(
            dtoCode = "deviceStatusCount",
            name = "设备状态数量",
            packageName = "example.stats",
            className = "DeviceStatusCountOutput",
            kind = LowcodeDtoKind.OUTPUT,
            contributorId = "example.example",
            fields = listOf(
                LsiLowcodeDtoField(
                    name = "total",
                    nullability = LowcodeDtoNullability.NON_NULL,
                    schema = LsiLowcodeApiSchema(type = "integer", format = "int64"),
                    description = "设备总数",
                ),
                LsiLowcodeDtoField(
                    name = "label",
                    nullability = LowcodeDtoNullability.NULLABLE,
                    schema = LsiLowcodeApiSchema(type = "string"),
                ),
            ),
        )

        val file = LowcodeDtoSourceGenerator.generateDefinitions(listOf(definition), emptyList()).single()
        val schema = definition.toLsiDtoSchema(emptyList())

        assertEquals("example.stats.generated.dto", file.packageName)
        assertTrue(file.content.contains("data class DeviceStatusCountOutput"))
        assertTrue(file.content.contains("val total: Long"))
        assertTrue(file.content.contains("/** 设备总数 */"))
        assertTrue(file.content.contains("val label: String?"))
        assertEquals(LsiLowcodeDtoRef(dtoCode = "deviceStatusCount"), schema.ref)
        assertEquals(setOf("total"), schema.required)
        assertEquals("设备总数", schema.properties.getValue("total").description)
        assertEquals("设备状态数量", schema.description)
    }

    @Test
    fun `view dto imports the explicitly configured existing entity source`() {
        val model = newsModel().copy(
            entityConfig = newsModel().entityConfig.copy(
                sourceMode = LowcodeEntitySourceMode.EXISTING,
                sourceQualifiedName = "example.content.News",
            ),
        )

        val view = LowcodeDtoSourceGenerator.generate(listOf(model))
