    @Test
    fun `view dto projects formula property from its entity`() {
        val model = newsModel().copy(
            entityConfig = newsModel().entityConfig.copy(
                formulaProperties = listOf(
                    LsiLowcodeFormulaProperty(
                        propertyCode = "displayTitle",
                        label = "展示标题",
                        kotlinType = "String",
                        kind = LowcodeFormulaKind.KOTLIN,
                        expression = "title.uppercase()",
                        dependencies = listOf("title"),
                    ),
                ),
            ),
            dtoDefinitions = listOf(
                LsiLowcodeDto(
                    dtoCode = "newsListView",
                    className = "NewsListView",
                    kind = LowcodeDtoKind.VIEW,
                    fields = listOf(LsiLowcodeDtoField("displayTitle")),
                ),
            ),
        )

        val view = LowcodeDtoSourceGenerator.generate(listOf(model)).single()
        val schema = model.toLsiDtoSchemas(listOf(model)).single()

        assertTrue(view.content.contains("val displayTitle: String"))
        assertTrue(view.content.contains("/** 展示标题 */"))
        assertTrue(view.content.contains("displayTitle = displayTitle"))
        assertTrue(schema.required.contains("displayTitle"))
        assertTrue(schema.properties.getValue("displayTitle").type == "string")
    }

    @Test
    fun `generates typed views input and entity mappings`() {
        val files = LowcodeDtoSourceGenerator.generate(listOf(newsModel()))
        val listView = files.single { file -> file.fileName == "NewsListView" }
        val request = files.single { file -> file.fileName == "NewsRequest" }

        assertTrue(listView.content.contains("val publishedAt: LocalDateTime?"))
        assertTrue(listView.content.contains("fun News.toNewsListView(): NewsListView"))
        assertTrue(listView.content.contains("publishedAt = publishedAt"))
        assertTrue(request.content.contains("val title: String,"))
        assertTrue(request.content.contains("val status: String? = null"))
        assertTrue(request.content.contains("val sortOrder: Int? = null"))
        assertTrue(request.content.contains("val enabled: Boolean? = null"))
        assertFalse(request.content.contains("fun News.toNewsRequest"))
    }

    @Test
    fun `removing dto metadata removes its generated file`() {
        val model = newsModel()
        val generated = LowcodeDtoSourceGenerator.generate(listOf(model))
        val afterDelete = LowcodeDtoSourceGenerator.generate(
            listOf(model.copy(dtoDefinitions = model.dtoDefinitions.filterNot { dto -> dto.dtoCode == "newsRequest" })),
        )

        assertTrue(generated.any { file -> file.fileName == "NewsRequest" })
        assertFalse(afterDelete.any { file -> file.fileName == "NewsRequest" })
    }

    @Test
    fun `view maps nullable relation fields and schemas from target metadata`() {
        val news = newsModel().copy(
            dtoDefinitions = listOf(
                LsiLowcodeDto(
                    dtoCode = "newsListView",
                    className = "NewsListView",
                    kind = LowcodeDtoKind.VIEW,
                    fields = listOf(LsiLowcodeDtoField("coverUrl", sourcePath = "coverFile.url")),
                ),
            ),
            relations = listOf(
                LowcodeRelationMeta(
                    id = 10,
                    modelId = 1,
                    orderNo = 1,
                    relationCode = "coverFile",
                    label = "coverFile",
                    relationKind = LowcodeRelationKind.MANY_TO_ONE,
                    targetModelId = 2,
                    targetModelCode = "storedFile",
                    targetPackageName = "example.file",
                    targetClassName = "StoredFile",
                    joinColumn = "cover_file_id",
                    mappedBy = null,
                    joinTable = null,
                    joinTableJoinColumn = null,
                    joinTableInverseColumn = null,
                    required = false,
                    listVisible = true,
                    formVisible = true,
                ),
            ),
        )
        val storedFile = newsModel().copy(
            id = 2,
            modelCode = "storedFile",
            packageName = "example.file",
            className = "StoredFile",
            dtoDefinitions = emptyList(),
            fields = listOf(field(20, "url", "String", "url", required = true).copy(modelId = 2)),
        )

        val view = LowcodeDtoSourceGenerator.generate(listOf(news, storedFile))
            .single { file -> file.fileName == "NewsListView" }
        val schema = news.toLsiDtoSchemas(listOf(news, storedFile)).single()

        assertTrue(view.content.contains("val coverUrl: String?"))
        assertTrue(view.content.contains("coverUrl = coverFile?.url"))
        assertTrue("coverUrl" !in schema.required)
        assertTrue(schema.properties.getValue("coverUrl").type == "string")
    }

