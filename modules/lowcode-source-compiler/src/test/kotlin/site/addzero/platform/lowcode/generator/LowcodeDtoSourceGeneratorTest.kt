    @Test
    fun `selection modes expand metadata fields and apply reverse exclusions`() {
        val news = newsModel().copy(
            relations = listOf(fileRelation()),
            dtoDefinitions = listOf(
                LsiLowcodeDto(
                    dtoCode = "scalarView",
                    className = "ScalarView",
                    kind = LowcodeDtoKind.VIEW,
                    selectionMode = LowcodeDtoSelectionMode.ALL_SCALAR_FIELDS,
                    excludedPaths = listOf("status"),
                ),
                LsiLowcodeDto(
                    dtoCode = "tableView",
                    className = "TableView",
                    kind = LowcodeDtoKind.VIEW,
                    selectionMode = LowcodeDtoSelectionMode.ALL_TABLE_FIELDS,
                    excludedPaths = listOf("publishedAt"),
                ),
                LsiLowcodeDto(
                    dtoCode = "deepView",
                    className = "DeepView",
                    kind = LowcodeDtoKind.VIEW,
                    selectionMode = LowcodeDtoSelectionMode.ALL_DEEP_FIELDS,
                    excludedPaths = listOf("coverFile.url"),
                ),
            ),
        )

        val files = LowcodeDtoSourceGenerator.generate(listOf(news), listOf(news, storedFileModel()))
            .associateBy(LowcodeGeneratedFile::fileName)

        assertTrue(files.getValue("ScalarView").content.contains("val title: String"))
        assertFalse(files.getValue("ScalarView").content.contains("val status:"))
        assertFalse(files.getValue("ScalarView").content.contains("coverFileId"))
        assertTrue(files.getValue("TableView").content.contains("val coverFileId: Long?"))
        assertFalse(files.getValue("TableView").content.contains("publishedAt"))
        assertTrue(files.getValue("DeepView").content.contains("val coverFileId: Long?"))
        assertEquals(1, Regex("val coverFileId:").findAll(files.getValue("DeepView").content).count())
        assertFalse(files.getValue("DeepView").content.contains("coverFileUrl"))
    }

    @Test
    fun `entity schema exposes shallow association objects and generated id views`() {
        val base = newsModel()
        val model = base.copy(
            fields = base.fields.map { field ->
                if (field.fieldCode == "title") {
                    field.copy(label = "标题", remark = "对外展示的新闻标题")
                } else {
                    field
                }
            },
            relations = listOf(
                fileRelation().copy(label = "封面文件"),
                attachmentsRelation().copy(label = "附件"),
            ),
        )
        val storedFile = storedFileModel()

        val schema = model.toLsiEntitySchema(listOf(model, storedFile))
        val coverFile = schema.properties.getValue("coverFile")
        val attachments = schema.properties.getValue("attachments")
        val contractSource = LowcodeRouteSourceGenerator.toContractSource(
            LsiLowcodeContract(
                contractCode = "news",
                name = "新闻",
                packageName = "example.news",
                className = "NewsService",
                path = "/news",
                dtoSchemas = listOf(schema),
            ),
        )

        assertEquals(LsiLowcodeDtoRef("news"), schema.ref)
        assertEquals("news_entity", schema.schemaName)
        assertEquals("新闻", schema.description)
        assertEquals("对外展示的新闻标题", schema.properties.getValue("title").description)
        assertEquals("object", coverFile.type)
        assertEquals("封面文件", coverFile.description)
        assertEquals("integer", coverFile.properties.getValue("id").type)
        assertEquals("string", coverFile.properties.getValue("url").type)
        assertTrue(schema.properties.containsKey("coverFileId"))
        assertEquals("封面文件编号", schema.properties.getValue("coverFileId").description)
        assertEquals("array", attachments.type)
        assertEquals("string", attachments.items?.properties?.getValue("url")?.type)
        assertTrue(schema.properties.containsKey("attachmentIds"))
        assertEquals("附件编号集合", schema.properties.getValue("attachmentIds").description)
        assertTrue(contractSource.contains("description = \"新闻\""))
        assertTrue(contractSource.contains("description = \"对外展示的新闻标题\""))
    }

